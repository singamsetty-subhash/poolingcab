CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255),
    phone VARCHAR(255),
    password_hash VARCHAR(255),
    role VARCHAR(32) NOT NULL DEFAULT 'USER',
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    license_number VARCHAR(255),
    vehicle_make VARCHAR(255),
    vehicle_model VARCHAR(255),
    vehicle_plate VARCHAR(255),
    vehicle_seats INT,
    verification_status VARCHAR(40),
    verification_note VARCHAR(500),
    CONSTRAINT fk_driver_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS rides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    driver_id BIGINT NOT NULL,
    origin VARCHAR(255),
    destination VARCHAR(255),
    departure TIMESTAMP,
    total_seats INT NOT NULL,
    available_seats INT NOT NULL,
    price_per_seat DOUBLE PRECISION NOT NULL,
    status VARCHAR(32),
    notes VARCHAR(1000),
    CONSTRAINT fk_ride_driver FOREIGN KEY (driver_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id BIGINT NOT NULL,
    passenger_id BIGINT NOT NULL,
    seats INT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    status VARCHAR(32),
    payment_method VARCHAR(20),
    payment_status VARCHAR(32),
    created_at TIMESTAMP,
    CONSTRAINT fk_booking_ride FOREIGN KEY (ride_id) REFERENCES rides(id),
    CONSTRAINT fk_booking_passenger FOREIGN KEY (passenger_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS pool_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    creator_id BIGINT NOT NULL,
    origin VARCHAR(255),
    destination VARCHAR(255),
    departure TIMESTAMP,
    seats_needed INT NOT NULL,
    seats_joined INT NOT NULL,
    target_price DOUBLE PRECISION NOT NULL,
    status VARCHAR(32),
    offered_by_id BIGINT,
    offered_ride_id BIGINT
);

CREATE TABLE IF NOT EXISTS pool_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    status VARCHAR(32),
    CONSTRAINT fk_member_pool FOREIGN KEY (pool_id) REFERENCES pool_request(id),
    CONSTRAINT fk_member_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uq_pool_member UNIQUE (pool_id, user_id)
);

CREATE TABLE IF NOT EXISTS payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    method VARCHAR(20),
    status VARCHAR(32),
    provider_reference VARCHAR(255),
    created_at TIMESTAMP,
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES bookings(id)
);
